"""
Write web/assets/data/generator_vs_verifier.js for the Generator vs Verifier page.

python scripts/export_generator_vs_verifier.py [--results_dir results]
"""
import argparse
import datetime
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from src.experiment_d.generator_verifier import collect


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--results_dir", "--output_dir", "--directory", default=str(ROOT / "results"))
    parser.add_argument("--out", default=str(ROOT / "web/assets/data/generator_vs_verifier.js"))
    args = parser.parse_args()

    rows = collect(args.results_dir)
    data = {"generated_at": datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%d %H:%M UTC"), "rows": rows}
    text = ("/* Generated by scripts/export_generator_vs_verifier.py from the run files in results/. Do not edit by hand. */\n"
            "window.GEN_VS_VER = " + json.dumps(data, indent=1) + ";\n")
    Path(args.out).write_text(text)
    print(f"{len(rows)} runs -> {args.out}")


if __name__ == "__main__":
    main()
