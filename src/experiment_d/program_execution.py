"""
Run the Python programs written for the 'program' prompt variant (test B1, prose vs program agreement).

The model answers with a ```python block defining solve(); the answer is what solve() returns. Each program
runs in its own `python -I -S` subprocess with a wall-clock timeout, CPU, memory and file-size limits, a
temporary working directory, a reduced set of builtins and imports restricted to a few math modules. This
guards against accidents in model-written code (loops, huge allocations, stray file writes); it is not a
security boundary, so only run responses generated by our own runs.

Statuses: ok (a finite number came back), no_code (no solve() found), syntax_error, runtime_error (an
exception, a blocked import or builtin included), timeout, non_numeric (solve() returned something that is
not a number, a bool, NaN or infinity).
"""
import json
import math
import os
import re
import subprocess
import sys
import tempfile
import textwrap
from concurrent.futures import ThreadPoolExecutor

TIMEOUT_SECONDS = 2.0
ALLOWED_MODULES = ("math", "fractions", "decimal", "statistics", "itertools", "functools", "datetime")
STATUSES = ("ok", "no_code", "syntax_error", "runtime_error", "timeout", "non_numeric")
RESULT_MARK = "__PROGRAM_RESULT__"

_FENCE = re.compile(r"```(?:python|py)?[ \t]*\n(.*?)```", re.S)
_DEF_SOLVE = re.compile(r"^[ \t]*def solve\s*\(", re.M)

# Runs inside the subprocess: limits, guarded builtins, then solve(); prints one marked JSON line.
_RUNNER = r'''
import builtins, io, json, math, sys
try:
    import resource
    for limit, value in ((resource.RLIMIT_CPU, 3), (resource.RLIMIT_FSIZE, 0), (resource.RLIMIT_AS, 1 << 30)):
        try:
            resource.setrlimit(limit, (value, value))
        except (ValueError, OSError):
            pass
except ImportError:
    pass
MARK, ALLOWED = sys.argv[1], set(json.loads(sys.argv[2]))
SAFE = ("abs all any bin bool chr dict divmod enumerate filter float format frozenset hex int isinstance "
        "issubclass iter len list map max min next oct ord pow print range repr reversed round set slice sorted "
        "str sum tuple zip ArithmeticError Exception IndexError KeyError OverflowError StopIteration "
        "TypeError ValueError ZeroDivisionError").split()
real_import = builtins.__import__
def guarded_import(name, globals=None, locals=None, fromlist=(), level=0):
    if level or name.split(".")[0] not in ALLOWED:
        raise ImportError("import not allowed: " + name)
    return real_import(name, globals, locals, fromlist, level)
safe = {k: getattr(builtins, k) for k in SAFE}
safe["__import__"] = guarded_import
safe["__build_class__"] = builtins.__build_class__
out = sys.stdout
def report(**kw):
    out.write(MARK + json.dumps(kw) + "\n")
    out.flush()
source = sys.stdin.read()
try:
    code = compile(source, "<program>", "exec")
except (SyntaxError, ValueError) as e:
    report(status="syntax_error", error=str(e)[:200]); sys.exit(0)
sys.stdout = io.StringIO()   # swallow the program's own prints
namespace = {"__builtins__": safe, "__name__": "__program__"}
try:
    exec(code, namespace)
    if not callable(namespace.get("solve")):
        raise NameError("solve() is not defined")
    result = namespace["solve"]()
except BaseException as e:
    report(status="runtime_error", error=(type(e).__name__ + ": " + str(e))[:200]); sys.exit(0)
if isinstance(result, str):
    try:
        result = float(result.replace(",", "").replace("$", "").strip())
    except ValueError:
        pass
if isinstance(result, bool) or not isinstance(result, (int, float)) and not hasattr(result, "__float__"):
    report(status="non_numeric", error=type(result).__name__); sys.exit(0)
try:
    value = int(result) if isinstance(result, int) else float(result)
except (TypeError, ValueError, OverflowError) as e:
    report(status="non_numeric", error=str(e)[:200]); sys.exit(0)
if isinstance(value, float) and not math.isfinite(value):
    report(status="non_numeric", error=repr(value)); sys.exit(0)
report(status="ok", value=value if isinstance(value, float) else str(value))
'''


def extract_program(text: str):
    """The code to run: the last fenced block that defines solve(), else everything from 'def solve' on
    (an unfenced or cut-off answer), dedented. None when the response defines no solve()."""
    blocks = [block for block in _FENCE.findall(text) if _DEF_SOLVE.search(block)]
    if blocks:
        return textwrap.dedent(blocks[-1])
    match = _DEF_SOLVE.search(text)
    if match is None:
        return None
    return textwrap.dedent(text[match.start():].split("```")[0])


def format_number(value) -> str:
    """'18' for 18.0 or 17.9999999, '18.5' for 18.5: the same spelling the prose extractor produces."""
    value = float(value) if not isinstance(value, int) else value
    if isinstance(value, int):
        return str(value)
    if abs(value - round(value)) < 1e-6:
        return str(int(round(value)))
    return f"{value:.6f}".rstrip("0").rstrip(".")


def run_program(code: str, timeout: float = TIMEOUT_SECONDS) -> dict:
    """Run one program; returns {status, answer, error}."""
    with tempfile.TemporaryDirectory() as workdir:
        try:
            proc = subprocess.run(
                [sys.executable, "-I", "-S", "-c", _RUNNER, RESULT_MARK, json.dumps(ALLOWED_MODULES)],
                input=code, capture_output=True, text=True, timeout=timeout, cwd=workdir,
                env={"PATH": os.environ.get("PATH", "")},
            )
        except subprocess.TimeoutExpired:
            return {"status": "timeout", "answer": None, "error": f"over {timeout}s"}
    lines = [line for line in proc.stdout.splitlines() if line.startswith(RESULT_MARK)]
    if not lines:  # killed by a resource limit, or crashed before reporting
        return {"status": "runtime_error", "answer": None, "error": (proc.stderr or f"exit {proc.returncode}")[-200:]}
    result = json.loads(lines[-1][len(RESULT_MARK):])
    if result["status"] != "ok":
        return {"status": result["status"], "answer": None, "error": result.get("error")}
    value = result["value"]
    return {"status": "ok", "answer": format_number(int(value) if isinstance(value, str) else value), "error": None}


def execute_response(text: str, timeout: float = TIMEOUT_SECONDS) -> dict:
    """Extract and run the program in one model response."""
    code = extract_program(text)
    if code is None:
        return {"status": "no_code", "answer": None, "error": None}
    return run_program(code, timeout)


def execute_many(texts, timeout: float = TIMEOUT_SECONDS, workers: int = 8) -> list:
    """execute_response over many responses in parallel, results in input order."""
    with ThreadPoolExecutor(max_workers=workers) as pool:
        return list(pool.map(lambda t: execute_response(t, timeout), texts))
